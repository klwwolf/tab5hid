public:
  //initial for all keyreg*
  enum Modifier:uint8_t{NONE=0x00,LCTRL=0x01,LSHIFT=0x02,LALT=0x04,LGUI=0x08,RCTRL=0x10,RSHIFT=0x20,RALT=0x40,RGUI=0x80};// RALT = AltGr
  enum Keynumber:uint8_t{NUM_1=0x1E,NUM_2=0x1F,NUM_3=0x20,NUM_4=0x21,NUM_5=0x22,NUM_6=0x23,NUM_7=0x24,NUM_8=0x25,NUM_9=0x26,NUM_0=0x27};
  enum Keymin:uint8_t{a=0x04,b=0x05,c=0x06,d=0x07,e=0x08,f=0x09,g=0x0A,h=0x0B,i=0x0C,j=0x0D,k=0x0E,l=0x0F,m=0x10,n=0x11,o=0x12,p=0x13,q=0x14,r=0x15,s=0x16,t=0x17,u=0x18,v=0x19,w=0x1A,x=0x1B,y=0x1C,z=0x1D};
  enum Keymaj:uint8_t{A=0x04,B=0x05,C=0x06,D=0x07,E=0x08,F=0x09,G=0x0A,H=0x0B,I=0x0C,J=0x0D,K=0x0E,L=0x0F,M=0x10,N=0x11,O=0x12,P=0x13,Q=0x14,R=0x15,S=0x16,T=0x17,U=0x18,V=0x19,W=0x1A,X=0x1B,Y=0x1C,Z=0x1D};
  enum Keycontrol:uint8_t{ENTER=0x28,ESC=0x29,BACKSPACE=0x2A,TAB=0x2B,SPACE=0x2C};
  enum Keysymbols:uint8_t{MINUS=0x2D,EQUAL=0x2E,LBRACKET=0x2F,RBRACKET=0x30,BACKSLASH=0x31,NON_US=0x32,SEMICOLON=0x33,QUOTE=0x34,GRAVE=0x35,COMMA=0x36,DOT=0x37,SLASH=0x38,CAPSLOCK=0x39};
  enum KeyFA:uint8_t{F1=0x3A,F2=0x3B,F3=0x3C,F4=0x3D,F5=0x3E,F6=0x3F,F7=0x40,F8=0x41,F9=0x42,F10=0x43,F11=0x44,F12=0x45};
  enum KeyFB:uint8_t{F13=0x68,F14=0x69,F15=0x6A,F16=0x6B,F17=0x6C,F18=0x6D,F19=0x6E,F20=0x6F,F21=0x70,F22=0x71,F23=0x72,F24=0x73};
